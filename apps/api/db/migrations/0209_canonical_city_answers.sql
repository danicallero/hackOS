CREATE FUNCTION pg_temp.canonical_city(answer jsonb) RETURNS jsonb
LANGUAGE sql STABLE AS $$
  SELECT CASE
    WHEN jsonb_typeof(answer) = 'object'
     AND jsonb_typeof(answer -> 'city') = 'string'
     AND jsonb_typeof(answer -> 'province') = 'string'
     AND jsonb_typeof(answer -> 'country') = 'string'
    THEN answer || jsonb_build_object(
      'city', btrim(answer ->> 'city'),
      'country', c.country,
      'province', CASE WHEN c.country = 'España'
        THEN COALESCE((SELECT canonical FROM city_es_region_alias
                        WHERE alias = lower(btrim(answer ->> 'province'))),
                      btrim(answer ->> 'province'))
        ELSE btrim(answer ->> 'province') END)
    ELSE answer
  END
  FROM (SELECT COALESCE((SELECT canonical FROM city_country_alias
                          WHERE alias = lower(btrim(answer ->> 'country'))),
                        btrim(answer ->> 'country')) AS country) c
$$;

CREATE FUNCTION pg_temp.canonical_city_answers(responses jsonb) RETURNS jsonb
LANGUAGE sql STABLE AS $$
  SELECT CASE WHEN jsonb_typeof(responses) = 'object'
    THEN COALESCE((SELECT jsonb_object_agg(key, pg_temp.canonical_city(value))
                     FROM jsonb_each(responses)), '{}'::jsonb)
    ELSE responses END
$$;

UPDATE application_responses
   SET responses = pg_temp.canonical_city_answers(responses)
 WHERE responses IS DISTINCT FROM pg_temp.canonical_city_answers(responses);

