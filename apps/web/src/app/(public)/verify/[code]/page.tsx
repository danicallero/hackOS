"use client";

// #1083: the page behind the QR and code printed on an attendance certificate.
// It shows the official document and the SHA-256 of its single stored copy, so a
// third party can check that the PDF they hold is that exact file.

import { XCircleIcon } from "@phosphor-icons/react/dist/csr/XCircle";
import { useParams } from "next/navigation";
import { useEffect, useState } from "react";
import { Brand } from "@/components/common/brand";
import { Spinner } from "@/components/common/spinner";
import { Button } from "@/components/ui/button";
import { api } from "@/lib/api";
import { API_URL } from "@/lib/env";
import { useLocale } from "@/lib/i18n";

async function sha256Hex(file: File): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", await file.arrayBuffer());
  return [...new Uint8Array(digest)].map((byte) => byte.toString(16).padStart(2, "0")).join("");
}

type State = { kind: "loading" } | { kind: "valid" } | { kind: "revoked" } | { kind: "missing" };

export default function VerifyCertificatePage() {
  const { t } = useLocale();
  const { code } = useParams<{ code: string }>();
  const [state, setState] = useState<State>({ kind: "loading" });
  const [sha256, setSha256] = useState<string | null>(null);
  const [superseded, setSuperseded] = useState(false);
  const [match, setMatch] = useState<boolean | null>(null);
  const endpoint = `/api/public/certificates/${encodeURIComponent(code)}`;

  useEffect(() => {
    let cancelled = false;
    api
      .get<{ status: "valid" | "revoked" }>(endpoint)
      .then((data) => !cancelled && setState({ kind: data.status }))
      .catch(() => !cancelled && setState({ kind: "missing" }));
    return () => {
      cancelled = true;
    };
  }, [endpoint]);

  // The copy is generated by the first PDF request, so the fingerprint is read once the viewer has loaded it.
  const readFingerprint = () =>
    void api
      .get<{ sha256: string | null; supersededAt: string | null }>(endpoint)
      .then((data) => {
        setSha256(data.sha256);
        setSuperseded(data.supersededAt !== null);
      })
      .catch(() => setSha256(null));

  return (
    <div className="flex h-dvh flex-col">
      <header className="bg-background border-b">
        <div className="mx-auto flex h-16 w-full max-w-6xl items-center px-6">
          <Brand className="text-2xl" />
        </div>
      </header>
      <main className="bg-muted/40 relative min-h-0 flex-1">
        {state.kind === "valid" ? (
          <div className="flex size-full flex-col">
            <iframe
              title={t("certificateVerifyTitle")}
              src={`${API_URL}${endpoint}/pdf`}
              onLoad={readFingerprint}
              className="min-h-0 flex-1 border-0"
            />
            {sha256 && (
              <div className="bg-background flex flex-wrap items-center gap-x-4 gap-y-2 border-t px-6 py-3 text-sm">
                {superseded && <span role="status">{t("certificateNewerVersion")}</span>}
                <span className="text-muted-foreground">SHA-256</span>
                <code className="min-w-0 flex-1 font-mono text-xs break-all">{sha256}</code>
                {match !== null && (
                  <span role="status">
                    {t(match ? "certificateFileMatches" : "certificateFileDiffers")}
                  </span>
                )}
                <Button asChild variant="outline" size="sm">
                  <label>
                    {t("certificateCheckFile")}
                    <input
                      type="file"
                      accept="application/pdf"
                      className="sr-only"
                      onChange={(event) => {
                        const file = event.target.files?.[0];
                        event.target.value = "";
                        if (file) void sha256Hex(file).then((hex) => setMatch(hex === sha256));
                      }}
                    />
                  </label>
                </Button>
              </div>
            )}
          </div>
        ) : (
          <div className="grid h-full place-items-center px-6" role="status" aria-live="polite">
            {state.kind === "loading" ? (
              <Spinner className="size-7" />
            ) : (
              <p className="text-muted-foreground flex items-center gap-2">
                <XCircleIcon className="size-5" weight="fill" aria-hidden="true" />
                {state.kind === "revoked"
                  ? t("certificateStatusRevoked")
                  : t("certificateNotFound")}
              </p>
            )}
          </div>
        )}
      </main>
    </div>
  );
}
